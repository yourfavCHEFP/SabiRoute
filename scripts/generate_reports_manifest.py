"""Deterministically regenerate REPORTS-MANIFEST.sha256 (R1 governance).

The attested set is a closed, explicit list (EXPLICIT_INCLUDE below) —
nothing is discovered by glob, so new files under reports/ are NEVER
silently included. Adding an artifact requires editing that list, which
is itself a governance decision. Byte-consistency semantics only: this
proves the listed bytes match the indexed hashes, not evidence
correctness, authorship, approval, or release completeness.

Usage:
    uv run python scripts/generate_reports_manifest.py            # rewrite manifest
    uv run python scripts/generate_reports_manifest.py --check    # exit 1 if stale
    uv run python scripts/generate_reports_manifest.py --output PATH  # write elsewhere

Verification (independent of this script):
    shasum -c REPORTS-MANIFEST.sha256
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = PROJECT_ROOT / "REPORTS-MANIFEST.sha256"

HEADER = """\
# REPORTS-MANIFEST.sha256 — B0 evidence index (Run 6 + R1 governance)
# Scope: 12 Markdown reports under reports/ + reports/provider_verification.json.
# Excluded: reports/mission-state-2026-10-26T095838.json (mission-state
# snapshot, evidentiary role not established); the reports/evidence/
# SabiChat closeout bundle (5 files, excluded per owner ruling — preserved
# unchanged, not invalidated); post-attestation reconciliation documents
# (e.g. reports/reconciliation-2026-10-31.md — out of the attested set by
# documented exclusion, never silent drift); top-level prompts/archives/
# working docs; and this manifest itself (no self-referential checksum).
# Entries: 13 total (12 Markdown + 1 JSON). The attestation tooling itself —
# this script, REPORTS-PROVENANCE.md, and REPORTS-MANIFEST.sha256 — is
# governance/tooling outside the hashed set (reviewed, not self-hashed).
# Format: "<sha256>  <repository-relative path>" (shasum -a 256 output).
# Generated by: uv run python scripts/generate_reports_manifest.py (deterministic).
# Verify with: shasum -c REPORTS-MANIFEST.sha256
"""

# Closed attested set, sorted (this order is the manifest order).
EXPLICIT_INCLUDE: tuple[str, ...] = (
    "reports/audit-acceptance-and-disposition.md",
    "reports/implementation_12h.md",
    "reports/mission-c-evidence-audit-2026-10-26.md",
    "reports/mission-runlog-2026-10-26T095838.md",
    "reports/mobilization-reconciliation-2026-10-26.md",
    "reports/my_scorecard.md",
    "reports/part-i-sprints-1-8-overnight-report-2026-10-26.md",
    "reports/pre-roadmap-audit.md",
    "reports/provider_verification.json",
    "reports/r02-kill-switch-remediation.md",
    "reports/reconciliation-plan.md",
    "reports/remediation-roadmap-and-gates.md",
    "reports/sprint-02b-unattended-core.md",
)


def render_manifest() -> str:
    """Hash every attested file; return the full manifest text."""
    lines = [HEADER]
    for rel in EXPLICIT_INCLUDE:
        digest = hashlib.sha256((PROJECT_ROOT / rel).read_bytes()).hexdigest()
        lines.append(f"{digest}  {rel}\n")
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate REPORTS-MANIFEST.sha256.")
    parser.add_argument("--check", action="store_true", help="Exit 1 if stale.")
    parser.add_argument("--output", type=Path, default=MANIFEST_PATH)
    args = parser.parse_args(argv)
    text = render_manifest()
    if args.check:
        current = args.output.read_text(encoding="utf-8")
        if current != text:
            print("REPORTS-MANIFEST.sha256 is stale; regenerate it.", file=sys.stderr)
            return 1
        print("REPORTS-MANIFEST.sha256 is fresh.")
        return 0
    args.output.write_text(text, encoding="utf-8")
    print(f"Wrote {args.output} ({len(EXPLICIT_INCLUDE)} entries).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
